CREATE OR REPLACE FUNCTION public.property_tours_touch_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER property_tour_requests_touch_updated_at
  BEFORE UPDATE ON public.property_tour_requests
  FOR EACH ROW EXECUTE FUNCTION public.property_tours_touch_updated_at();